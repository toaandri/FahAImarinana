-- Import:
--   psql -U fanilo -d fanilo -f Backend/database/fanilo_postgresql.sql
--
BEGIN;

CREATE TABLE IF NOT EXISTS sources_surveillees (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL,
    type VARCHAR(30) NOT NULL
        CHECK (type IN ('Facebook', 'X', 'Web', 'RSS')),
    url VARCHAR(500) NOT NULL,
    statut VARCHAR(15) NOT NULL DEFAULT 'Actif'
        CHECK (statut IN ('Actif', 'Inactif')),
    frequence_scan_secondes INTEGER NOT NULL DEFAULT 900
        CHECK (frequence_scan_secondes >= 60),
    derniere_verification TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS signaux_bruts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id INTEGER NOT NULL
        REFERENCES sources_surveillees(id) ON DELETE RESTRICT,
    contenu_brut TEXT NOT NULL,
    contenu_normalise TEXT NOT NULL,
    url_origine VARCHAR(500) NOT NULL,
    horodatage_publication TIMESTAMPTZ NOT NULL,
    auteur VARCHAR(150),
    nombre_interactions INTEGER NOT NULL DEFAULT 0
        CHECK (nombre_interactions >= 0),
    niveau_viralite DOUBLE PRECISION NOT NULL DEFAULT 0
        CHECK (niveau_viralite >= 0 AND niveau_viralite <= 100),
    mots_cles_detectes JSONB NOT NULL DEFAULT '[]'::jsonb,
    est_urgent BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS drafts_ia (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signal_id INTEGER NOT NULL
        REFERENCES signaux_bruts(id) ON DELETE RESTRICT,
    titre_suggere VARCHAR(250) NOT NULL,
    synthese_ia TEXT NOT NULL,
    score_credibilite_indicatif DOUBLE PRECISION NOT NULL
        CHECK (score_credibilite_indicatif >= 0 AND score_credibilite_indicatif <= 100),
    sources_croisees JSONB NOT NULL DEFAULT '[]'::jsonb,
    statut VARCHAR(25) NOT NULL DEFAULT 'En_Attente'
        CHECK (statut IN ('En_Attente', 'En_Cours', 'Rejete')),
    horodatage TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_drafts_ia_signal_id UNIQUE (signal_id)
);

CREATE TABLE IF NOT EXISTS articles_certifies (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id INTEGER
        REFERENCES drafts_ia(id) ON DELETE SET NULL,
    titre_final VARCHAR(250) NOT NULL,
    corps_article TEXT NOT NULL,
    categorie VARCHAR(50) NOT NULL,
    statut_verification VARCHAR(20) NOT NULL
        CHECK (statut_verification IN ('Vrai', 'Faux', 'Trompeur')),
    id_journaliste_validateur INTEGER NOT NULL,
    horodatage_validation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    contenu_optimise_sms VARCHAR(480) NOT NULL
);

CREATE TABLE IF NOT EXISTS historique_sms (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_expediteur VARCHAR(30) NOT NULL,
    message_recu TEXT NOT NULL,
    message_envoye TEXT NOT NULL,
    horodatage TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    statut_reponse VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS utilisateurs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    mot_de_passe_hash VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'Journaliste'
        CHECK (role IN ('Journaliste', 'Editeur')),
    actif BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS contacts_journalistes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id INTEGER NOT NULL REFERENCES utilisateurs(id) ON DELETE CASCADE,
    numero_telephone VARCHAR(30) NOT NULL UNIQUE,
    alertes_actives BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS documents_recherche (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre VARCHAR(250) NOT NULL,
    contenu TEXT NOT NULL,
    url VARCHAR(500),
    est_certifie BOOLEAN NOT NULL DEFAULT FALSE,
    cree_le TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_signaux_source_date
    ON signaux_bruts (source_id, horodatage_publication DESC);

CREATE INDEX IF NOT EXISTS idx_signaux_urgence
    ON signaux_bruts (est_urgent, horodatage_publication DESC)
    WHERE est_urgent = TRUE;

CREATE INDEX IF NOT EXISTS idx_drafts_statut_date
    ON drafts_ia (statut, horodatage DESC);

CREATE INDEX IF NOT EXISTS idx_articles_publication
    ON articles_certifies (horodatage_validation DESC);

CREATE INDEX IF NOT EXISTS idx_sms_numero_date
    ON historique_sms (numero_expediteur, horodatage DESC);

CREATE INDEX IF NOT EXISTS idx_documents_recherche_certifies
    ON documents_recherche (est_certifie, cree_le DESC);

-- View backend destinée aux requêtes publiques validées.
-- Elle ne contient jamais les brouillons IA ni les signaux bruts.
CREATE OR REPLACE VIEW articles_certifies_publics AS
SELECT
    id,
    titre_final,
    corps_article,
    categorie,
    statut_verification,
    horodatage_validation,
    contenu_optimise_sms
FROM articles_certifies
WHERE statut_verification IN ('Vrai', 'Faux', 'Trompeur');

COMMIT;