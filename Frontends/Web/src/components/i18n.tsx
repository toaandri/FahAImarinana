type TranslationContextValue = {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (key: MessageKey, values?: Record<string, string | number>) => string;
};

const LanguageContext = createContext<TranslationContextValue | null>(null);

function isAppLanguage(value: string | null): value is AppLanguage {
  return value === 'mg' || value === 'fr' || value === 'en';
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(() => {
    try {
      const saved = globalThis.localStorage?.getItem(storageKey) ?? null;
      return isAppLanguage(saved) ? saved : 'fr';
    } catch (error) {
      console.error('Unable to read the saved interface language.', error);
      return 'fr';
    }
  });

  const setLanguage = useCallback((next: AppLanguage) => {
    setLanguageState(next);
    try {
      globalThis.localStorage?.setItem(storageKey, next);
    } catch (error) {
      console.error('Unable to persist the interface language.', error);
    }
  }, []);

  const value = useMemo<TranslationContextValue>(() => ({
    language,
    setLanguage,
    t: (key, values) => {
      let text: string = messages[language][key];
      if (values) {
        for (const [name, replacement] of Object.entries(values)) {
          text = text.replaceAll(`{${name}}`, String(replacement));
        }
      }
      return text;
    },
  }), [language, setLanguage]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useI18n must be used within LanguageProvider.');
  return context;
}

